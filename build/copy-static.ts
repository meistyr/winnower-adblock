/**
 * Copy hand-written extension assets into the generated extension/ tree.
 *
 * Only files the browser loads as they are (the HTML pages). The TypeScript is
 * bundled into extension/ by build/compile.ts, and tsconfig.json and the
 * shared/ modules are source, not assets.
 *
 * extension/ is gitignored and rebuilt from scratch, so anything hand-written
 * must live in src/ and be copied in. Writing directly into extension/ produces
 * a build that works locally and is silently broken on a fresh clone.
 */
import { copyFile, mkdir, readdir } from 'node:fs/promises';

const SRC = new URL('../src/', import.meta.url);
const DEST = new URL('../extension/', import.meta.url);

await mkdir(DEST, { recursive: true });
const files = (await readdir(SRC, { withFileTypes: true }))
  .filter((e) => e.isFile() && !e.name.endsWith('.ts') && e.name !== 'tsconfig.json')
  .map((e) => e.name);
for (const f of files) {
  await copyFile(new URL(f, SRC), new URL(f, DEST));
  console.log('  copied  src/' + f);
}

// Toolbar icons and the popup logo are generated by `npm run brand` and committed, so a normal
// update never needs the rasteriser.
const ICONS_SRC = new URL('../brand/icons/', import.meta.url);
const ICONS_DEST = new URL('icons/', DEST);
await mkdir(ICONS_DEST, { recursive: true });
const icons = (await readdir(ICONS_SRC)).filter((f) => f.endsWith('.png') || f.endsWith('.svg'));
for (const f of icons) await copyFile(new URL(f, ICONS_SRC), new URL(f, ICONS_DEST));
console.log(`  copied  brand/icons/ (${icons.length} files)`);

// The licence, for the popup footer's GPL-3.0 link. .txt so Chrome shows it as
// text instead of offering an extensionless file as a download.
await copyFile(new URL('../LICENSE', import.meta.url), new URL('LICENSE.txt', DEST));
console.log('  copied  LICENSE -> LICENSE.txt');

console.log(`\u2713 ${files.length} static file(s) and ${icons.length} icon(s) copied into extension/`);
