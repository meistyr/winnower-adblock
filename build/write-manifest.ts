/**
 * Generate extension/manifest.json from lists.config.ts.
 *
 * Generated rather than hand-written so the ruleset declarations cannot drift
 * out of sync with the lists actually converted. A manifest naming a ruleset
 * file that does not exist makes Chrome reject the whole extension at load.
 */
import { readFile, writeFile, access } from 'node:fs/promises';
import { SCRIPTLETS_VERSION } from '@adguard/scriptlets';
import { LISTS } from './lists.config.ts';
import { SCRIPTLET_GROUPS } from './scriptlet-rules.ts';
import type { DynamicScript, RulesetEntry } from '../src/shared/catalogue.ts';

const EXT_DIR = new URL('../extension/', import.meta.url);
const LISTS_DIR = new URL('../lists/', import.meta.url);

// Generated by `npm run brand`. The dark-background set is the static default;
// the service worker swaps the toolbar icon to match Chrome's light or dark mode.
const iconSet = (ground: 'light' | 'dark', sizes: number[]) => Object.fromEntries(sizes.map((s) => [String(s), `icons/mark-on-${ground}-${s}.png`]));

// package.json is the one place the version is set; the popup footer reads it back
// from the manifest at runtime.
const { version } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')) as { version: string };

const manifest = {
  manifest_version: 3,
  name: 'winnower',
  version,
  description: 'A free, open-source content blocker. Every page in its final shape.',
  // The website link on winnower's details page in chrome://extensions.
  homepage_url: 'https://winnower.meistyr.tech',
  minimum_chrome_version: '121',

  permissions: [
    'declarativeNetRequest',
    'declarativeNetRequestFeedback',
    'scripting',
    'storage',
    'webNavigation', // resets the per-tab blocked counter on navigation
    'offscreen', // a hidden page that can see light/dark mode, for the toolbar icon
  ],

  icons: iconSet('dark', [16, 32, 48, 128]),

  action: {
    default_popup: 'popup.html',
    default_title: 'winnower',
    default_icon: iconSet('dark', [16, 32]),
  },

  // Broad by design. A store extension would have to request per-site access,
  // which is exactly why uBlock Origin Lite's default mode is weaker on sites
  // needing scriptlets. Self-authored and locally loaded, so the tradeoff of
  // least-privilege for capability is ours to make.
  host_permissions: ['<all_urls>'],

  background: { service_worker: 'sw.js' },

  content_scripts: [
    // Cosmetic filtering. The generic stylesheet is injected natively here so
    // it lands before first paint — no JS, no flash. content.js handles only
    // the domain-specific selectors, which it fetches via the service worker.
    // ISOLATED world (the default) is required: it needs chrome.runtime.
    //
    // all_frames injects a SEPARATE copy into every embedded frame, each of
    // which asks the worker its own question. That is why the worker decides
    // on/off from the tab rather than from the hostname the frame reports.
    {
      matches: ['<all_urls>'],
      css: ['cosmetic/generic.css'],
      js: ['content.js'],
      run_at: 'document_start',
      all_frames: true,
    },
  ],

  declarative_net_request: {
    rule_resources: LISTS.map((list) => ({
      id: list.name,
      enabled: list.enabled,
      path: `rules/${list.name}.json`,
    })).concat([
      // Its own ruleset so it can be switched off alone. DNR cannot tell a
      // popunder from a deliberate visit to the same domain, so these rules
      // also block navigating there on purpose — right for popunder farms,
      // but the one part of winnower most likely to surprise someone.
      { id: 'popup', enabled: true, path: 'rules/popup.json' },
    ]),
  },
};

async function main() {
  // Assert every declared ruleset file actually exists. Chrome's failure mode
  // for a missing path is to reject the entire extension, with an error that
  // does not name the offending file.
  const missing: string[] = [];
  for (const r of manifest.declarative_net_request.rule_resources) {
    try {
      await access(new URL(r.path, EXT_DIR));
    } catch {
      missing.push(r.path);
    }
  }
  const dynamicFiles = SCRIPTLET_GROUPS.map((g) => `scriptlets/${g.id}.js`);
  const iconFiles = (['light', 'dark'] as const).flatMap((g) => Object.values(iconSet(g, [16, 32, 48, 128])));
  for (const extra of ['sw.js', 'cosmetic/generic.css', 'popup-guard.js', 'popup.html', 'popup.js', 'offscreen.html', 'offscreen.js', 'LICENSE.txt', 'icons/lockup-popup.svg', ...iconFiles, ...dynamicFiles]) {
    try {
      await access(new URL(extra, EXT_DIR));
    } catch {
      missing.push(extra);
    }
  }

  for (const cs of manifest.content_scripts ?? []) {
    for (const js of cs.js ?? []) {
      try {
        await access(new URL(js, EXT_DIR));
      } catch {
        missing.push(js);
      }
    }
  }

  if (missing.length) {
    console.error('Missing ruleset files — run `npm run convert` first:');
    for (const m of missing) console.error(`  ! ${m}`);
    process.exitCode = 1;
    return;
  }

  await writeFile(new URL('manifest.json', EXT_DIR), JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  // CREDITS.txt. A built extension contains rules converted from these lists, and
  // some are CC BY, which requires attribution wherever they are redistributed. The
  // homepage and licence come from each list's own header as fetched, so the credits
  // stay true to what was actually built rather than to what was typed here once.
  const credits: string[] = [
    `winnower ${version}`,
    'https://github.com/meistyr/winnower-adblock',
    'Copyright (C) 2026 meistyr.tech. Licensed GPL-3.0-or-later, see LICENSE.txt.',
    'This program comes with ABSOLUTELY NO WARRANTY.',
    '',
    'This extension contains blocking rules converted from the filter lists below.',
    'Each list remains under its own licence, as declared in its header.',
    '',
  ];
  for (const list of LISTS) {
    const text = await readFile(new URL(`${list.name}.txt`, LISTS_DIR), 'utf8');
    const field = (re: RegExp) =>
      text.split('\n', 60).map((line) => re.exec(line.trim())?.[1]?.trim()).find(Boolean);
    const title = field(/^!\s*Title\s*:\s*(.+)$/i) ?? list.title ?? list.name;
    const homepage = field(/^!\s*Homepage\s*:\s*(.+)$/i) ?? list.url;
    const licence = field(/^!\s*Licen[cs]e\s*:\s*(.+)$/i) ?? 'none stated in the list; see its homepage';
    credits.push(title, `  Homepage: ${homepage}`, `  Licence:  ${licence}`, `  Source:   ${list.url}`, '');
  }
  credits.push(
    `Scriptlets: @adguard/scriptlets ${SCRIPTLETS_VERSION}, GPL-3.0`,
    '  https://github.com/AdguardTeam/Scriptlets',
    '',
  );
  await writeFile(new URL('CREDITS.txt', EXT_DIR), credits.join('\n'), 'utf8');

  // Catalogue for the popup UI, so it can show grouped, human-readable lists
  // without duplicating lists.config.ts by hand.
  const catalogue: RulesetEntry[] = [
    ...LISTS.map((l) => ({ id: l.name, group: l.group, tier: l.tier, note: l.note })),
    { id: 'popup', group: 'popups', tier: 2, note: 'Popunders and new-window ads' },
  ];
  await writeFile(new URL('rulesets.json', EXT_DIR), JSON.stringify(catalogue, null, 2), 'utf8');

  // MAIN-world scripts are registered dynamically by the service worker rather
  // than declared above. They run at document_start with no chrome.storage and
  // no synchronous signal available that early, so they cannot check the
  // allowlist themselves — and declared in the manifest they cannot be switched
  // off at all. That is why the kill switches failed on YouTube: its blocking
  // is entirely these scripts. Registered dynamically, the worker can exclude
  // allowlisted sites and drop them entirely when the master switch is off.
  //
  // world: 'MAIN' and runAt: 'document_start' are both load-bearing. ISOLATED
  // cannot see page globals like ytInitialPlayerResponse, and document_idle
  // fires long after the player has read them.
  const dynamicScripts: DynamicScript[] = [
    {
      id: 'winnower-popup-guard',
      matches: ['<all_urls>'],
      js: ['popup-guard.js'],
      runAt: 'document_start',
      world: 'MAIN',
      allFrames: false,
    },
    ...SCRIPTLET_GROUPS.map((g): DynamicScript => ({
      id: `winnower-scriptlets-${g.id}`,
      matches: g.matches,
      js: [`scriptlets/${g.id}.js`],
      runAt: 'document_start',
      world: 'MAIN',
      allFrames: true,
    })),
  ];
  await writeFile(new URL('dynamic-scripts.json', EXT_DIR), JSON.stringify(dynamicScripts, null, 2), 'utf8');

  const ungrouped = catalogue.filter((c) => !c.group);
  if (ungrouped.length) {
    // The popup renders by group, so an ungrouped list would silently vanish
    // from the UI while still running — the kind of thing nobody would notice.
    console.error('Lists with no group (would be invisible in the popup):');
    for (const u of ungrouped) console.error(`  ! ${u.id}`);
    process.exitCode = 1;
    return;
  }

  const enabled = manifest.declarative_net_request.rule_resources.filter((r) => r.enabled);
  console.log(`✓ manifest.json: ${manifest.declarative_net_request.rule_resources.length} rulesets declared, ${enabled.length} enabled by default`);
  for (const r of manifest.declarative_net_request.rule_resources) {
    console.log(`    ${r.enabled ? 'on ' : 'off'}  ${r.id}`);
  }
}

await main();
